export const BENGALI_DIGITS: Record<string, string> = {
  '0': '০',
  '1': '১',
  '2': '২',
  '3': '৩',
  '4': '৪',
  '5': '৫',
  '6': '৬',
  '7': '৭',
  '8': '৮',
  '9': '৯',
};

export const HINDI_DIGITS: Record<string, string> = {
  '0': '०',
  '1': '१',
  '2': '२',
  '3': '३',
  '4': '४',
  '5': '५',
  '6': '६',
  '7': '७',
  '8': '८',
  '9': '९',
};

export function formatNumber(val: number | string, lang: Language): string {
  const str = String(val);
  if (lang === 'bn') {
    return str.replace(/[0-9]/g, (w) => BENGALI_DIGITS[w] || w);
  }
  if (lang === 'hi') {
    return str.replace(/[0-9]/g, (w) => HINDI_DIGITS[w] || w);
  }
  return str;
}

